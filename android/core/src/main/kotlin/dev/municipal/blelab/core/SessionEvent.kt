package dev.municipal.blelab.core

data class SessionEvent(
    val sessionId: String,
    val role: String,
    val manufacturer: String,
    val model: String,
    val osVersion: String,
    val appVersion: String,
    val protocol: String,
    val advertiseMethod: String,
    val periodSeconds: Int,
    val intervalMs: Int,
    val connectable: Boolean,
    val eventType: String,
    val monotonicMs: Long,
    val wallTimeUtc: String,
    val wallEpochMs: Long,
    val code: Long? = null,
    val major: Int? = null,
    val minor: Int? = null,
    val rssi: Int? = null,
    val classification: String? = null,
    val boundaryGrace: Boolean? = null,
    val captureLatencyMs: Long? = null,
    val success: Boolean? = null,
    val errorCode: String? = null,
    val errorMessage: String? = null,
)

data class LabSummary(
    val captureAttempts: Int,
    val captureSuccesses: Int,
    val captureFailures: Int,
    val successPercent: Double?,
    val captureMeanMs: Double?,
    val captureP50Ms: Long?,
    val captureP95Ms: Long?,
    val captureP99Ms: Long?,
    val transitionCount: Int,
    val transitionMeanMs: Double?,
    val transitionP50Ms: Long?,
    val transitionP95Ms: Long?,
    val missedWindows: Long?,
    val missedWindowsEstimated: Boolean,
    val currentObservations: Int,
    val previousObservations: Int,
    val nextObservations: Int,
    val otherObservations: Int,
    val boundaryGraceObservations: Int,
    val emitterErrors: Int,
    val receiverErrors: Int,
    val recoveries: Int,
)
